export function selectLocale(locales: string[], language: Language) {
  const preferred = language === 'ar' ? ['ar-LB', 'ar-SA'] : ['en-US', 'en-GB'];
  return preferred.map(tag => locales.find(value => value.toLowerCase() === tag.toLowerCase())).find(Boolean)
    ?? locales.find(tag => tag.toLowerCase().split(/[-_]/)[0] === language);
}

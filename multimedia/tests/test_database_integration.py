def test_transaction_rollback_cleans_candidate_file(stored):
    repository, save, session_id, _, _ = stored
    identifier = uuid4()

    def invalid_row(**kwargs):
        row = Frame(**kwargs)
        row.session_id = None  # Force a real MySQL NOT NULL violation at flush.
        return row

    with patch("database.repository.Frame", side_effect=invalid_row):
        with pytest.raises(RepositoryError):
            save(frame_id=identifier)
    assert repository.get_frame(identifier) is None
    assert not list(repository.storage_root.rglob("*.jpg"))


def test_delete_only_target_frame(stored):
    repository, save, _, _, _ = stored
    first, second = save(), save()
    path = repository.storage_root / repository.get_frame(first).image_path
    assert repository.delete_frame(first)
    assert repository.get_frame(first) is None and not path.exists()
    assert repository.get_frame(second) is not None


def test_nullable_embedding(stored):
    repository, save, _, _, _ = stored
    identifier = save()
    record = repository.get_frame(identifier)
    assert record.embedding is None and record.embedding_model is None
    with repository.sessions() as sql_session:
        assert sql_session.scalar(text("SELECT embedding IS NULL FROM frames WHERE frame_id = :id"),
                                  {"id": str(identifier)}) == 1



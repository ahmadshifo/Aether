def test_database_connection(live_database):
    assert live_database.check()["mysql_version"].startswith(("8.0.", "8.4."))


def test_native_json_storage(live_database, stored):
    repository, save, _, _, vector = stored
    identifier = save(objects=["door", "sign"], embedding=vector, embedding_model=EMBEDDING_MODEL)
    with live_database.engine.connect() as connection:
        row = connection.execute(text("SELECT JSON_TYPE(objects), JSON_TYPE(embedding), "
                                      "JSON_LENGTH(embedding), JSON_UNQUOTE(JSON_EXTRACT(objects, '$[0]')) "
                                      "FROM frames WHERE frame_id = :id"), {"id": str(identifier)}).one()
        assert tuple(row) == ("ARRAY", "ARRAY", 1536, "door")
        types = dict(connection.execute(text("SELECT COLUMN_NAME, DATA_TYPE FROM information_schema.columns "
                                             "WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'frames' "
                                             "AND COLUMN_NAME IN ('objects', 'embedding')")).all())
        assert types == {"objects": "json", "embedding": "json"}


def test_table_fields_and_indexes(live_database):
    inspector = inspect(live_database.engine)
    assert {column["name"] for column in inspector.get_columns("frames")} == set(Frame.__table__.columns.keys())
    indexes = {index["name"] for index in inspector.get_indexes("frames")}
    assert {"frames_session_time_idx", "frames_expires_at_idx"} <= indexes


def test_frame_insertion_and_insertion_based_retention(stored):
    repository, save, session_id, _, vector = stored
    frame_id = save(ocr_text="ROOM 205", objects=["door", "sign"], caption="A door.",
                    embedding=vector, embedding_model=EMBEDDING_MODEL)
    record = repository.get_frame(frame_id)
    assert record.frame_id == frame_id and record.session_id == session_id
    assert record.created_at > record.captured_at
    assert abs((record.expires_at - record.created_at).total_seconds() - 86400) < 1


def test_frame_retrieval(stored):
    repository, save, _, _, _ = stored
    frame_id = save(ocr_text="الغرفة ٢٠٥", objects=["door"], caption="A door.",
                    source_frame_index=30, video_timestamp_ms=1000.5,
                    captured_at=datetime(2026, 1, 1, 4, 30, 2, 123456,
                                         tzinfo=timezone(timedelta(hours=2))))
    record = repository.get_frame(frame_id)
    assert record.ocr_text == "الغرفة ٢٠٥" and record.objects == ["door"]
    assert record.source_frame_index == 30 and record.video_timestamp_ms == 1001
    assert record.captured_at == datetime(2026, 1, 1, 2, 30, 2, 123456, tzinfo=UTC)
    assert record.created_at.tzinfo == UTC and record.expires_at.tzinfo == UTC
    with repository.sessions() as sql_session:
        raw = sql_session.execute(text("SELECT captured_at FROM frames WHERE frame_id = :id"),
                                  {"id": str(frame_id)}).scalar_one()
        assert raw.tzinfo is None and raw == record.captured_at.replace(tzinfo=None)



def test_timeline_and_keyset_pagination(stored):
    repository, save, session_id, _, _ = stored
    capture = datetime(2020, 1, 1, tzinfo=UTC)
    older = save(captured_at=capture)
    newest = [save(captured_at=capture + timedelta(seconds=1)) for _ in range(2)]
    expected = sorted(newest, reverse=True) + [older]
    first = repository.list_frames(session_id, limit=1)
    second = repository.list_frames(session_id, limit=2,
                                    before=FrameCursor(first[0].captured_at, first[0].frame_id))
    assert [record.frame_id for record in first + second] == expected



"""Generate repeatable MySQL 8.0.17+/8.4 SQL from the canonical ORM models."""

import argparse
from pathlib import Path

from sqlalchemy.dialects import mysql
from sqlalchemy.schema import CreateIndex, CreateTable

from .models import Base, Frame

SCHEMA_FILE = Path(__file__).with_name("schema.sql")


def create_table_sql(table=None) -> str:
    dialect = mysql.dialect()
    table = Frame.__table__ if table is None else table
    ddl = str(CreateTable(table, if_not_exists=True).compile(dialect=dialect)).strip()
    if not table.indexes:
        return ddl
    # MySQL has no CREATE INDEX IF NOT EXISTS. Inline indexes also make the
    # generated SQL file repeatable without procedures or destructive DDL.
    prefix, closing, suffix = ddl.rpartition("\n)")
    if not closing:
        raise RuntimeError("Unexpected MySQL CREATE TABLE format.")
    indexes = []
    for index in sorted(table.indexes, key=lambda item: item.name):
        sql = str(CreateIndex(index).compile(dialect=dialect))
        indexes.append(sql.replace("CREATE INDEX ", "INDEX ", 1).replace(f" ON {table.name} ", " ", 1))
    return prefix + ",\n\t" + ",\n\t".join(indexes) + closing + suffix


def render_schema() -> str:
    return ("-- Generated by python -m database.schema --write; edit models.py, not this file.\n"
            "-- MySQL Community 8.0.17+ or 8.4 LTS. Existing tables and records are never dropped.\n"
            + "\n\n".join("\n".join(line.rstrip() for line in create_table_sql(table).splitlines()) + ";"
                           for table in Base.metadata.sorted_tables) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    if args.write:
        SCHEMA_FILE.write_text(render_schema(), encoding="utf-8")
        print("Updated database/schema.sql")
    else:
        print(render_schema())
